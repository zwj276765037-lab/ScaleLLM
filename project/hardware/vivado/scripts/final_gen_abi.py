#!/usr/bin/env python3
"""Generate one shared ABI's SV constants; --check detects map drift."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def rendered():
    spec = json.loads((ROOT / "source/final/abi.json").read_text())
    lines = ["// Generated by final_gen_abi.py from source/final/abi.json."]
    for section, prefix in (("ids", "ID"), ("registers", "CSR"),
                            ("errors", "ERR"), ("actions", "ACTION"),
                            ("opcodes", "OP")):
        for key, value in spec[section].items():
            lines.append(f"localparam [31:0] FINAL_{prefix}_{key.upper()} = 32'h{value:08x};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = ROOT / "rtl/integration/hap_scalellm_final_abi.svh"
    value = rendered()
    if args.check:
        if not destination.is_file() or destination.read_text() != value:
            raise SystemExit("final SV ABI constants differ from shared JSON")
    else:
        destination.write_text(value)


if __name__ == "__main__":
    main()
